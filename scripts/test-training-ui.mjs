import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";

const require = createRequire(import.meta.url);
let playwright;
try { playwright = require("playwright"); } catch { playwright = require(join(tmpdir(), "lidea-browser-tools/node_modules/playwright")); }
const browser = await playwright.chromium.launch({ channel: "chrome", headless: true });
const origin = process.env.LIDEA_TEST_URL || "http://localhost:3002";
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const id = "pre-incubation-2026-1";
try {
  // Exercise the existing local test workspace without writing test applicants to a real database.
  await context.addInitScript((now) => { Date.now = () => now; }, Date.parse("2026-11-02T16:15:00Z"));
  await context.route("**/api/trainings?*", (route) => route.fulfill({ status: 503, json: { ok: false } }));
  await context.route("https://zoom.us/**", (route) => route.fulfill({ status: 200, contentType: "text/html", body: "<h1>Test Zoom meeting</h1>" }));
  const admin = await context.newPage();
  await admin.goto(`${origin}/admin/program?egitim=${id}`);
  await admin.getByRole("button", { name: "Bağlantı ve Saati Düzenle", exact: true }).click();
  await admin.getByLabel("Zoom / Toplantı bağlantısı", { exact: true }).fill("https://zoom.us/j/original");
  await admin.getByLabel("Başlangıç saati", { exact: true }).fill("20:00");
  await admin.getByLabel("Bitiş saati", { exact: true }).fill("22:00");
  await admin.getByRole("button", { name: "Eğitimi Kaydet", exact: true }).click();
  await admin.getByText("Eğitim bu tarayıcıdaki çalışma alanına kaydedildi.", { exact: true }).waitFor();
  const founder = await context.newPage();
  await founder.goto(`${origin}/girisimci?egitim=${id}`);
  const schedule = founder.getByRole("region", { name: "Eğitim takvimi", exact: true });
  await schedule.getByRole("button", { name: "Takip Et ve Hatırlat", exact: true }).click();
  await schedule.getByRole("button", { name: "Takibi Bırak", exact: true }).waitFor();
  assert.equal(await founder.getByRole("button", { name: "Bağlantı ve Saati Düzenle", exact: true }).count(), 0);
  assert.equal(await founder.getByLabel("Zoom / Toplantı bağlantısı", { exact: true }).count(), 0);
  const reminders = await founder.evaluate(() => JSON.parse(localStorage.getItem("lidea-notifications")).filter((notice) => notice.trainingId && notice.type === "Hatırlatma"));
  assert.ok(reminders.some((notice) => notice.recipients.some((recipient) => recipient.email === "tester@lideagirisim.com")));
  assert.ok(reminders.some((notice) => notice.recipients.some((recipient) => recipient.email === "admin@lideagirisim.com")));
  await admin.getByRole("button", { name: "Bağlantı ve Saati Düzenle", exact: true }).click();
  await admin.getByLabel("Zoom / Toplantı bağlantısı", { exact: true }).fill("https://zoom.us/j/updated");
  await admin.getByRole("button", { name: "Eğitimi Kaydet", exact: true }).click();
  const popupPromise = founder.waitForEvent("popup");
  await schedule.getByRole("button", { name: "Eğitime Katıl", exact: true }).click();
  const popup = await popupPromise;
  await popup.waitForURL("https://zoom.us/j/updated");
  await popup.close();
  const downloadPromise = founder.waitForEvent("download");
  await schedule.getByRole("button", { name: "Takvime Ekle (.ics)", exact: true }).click();
  assert.ok((await downloadPromise).suggestedFilename().endsWith(".ics"));
  await schedule.getByRole("button", { name: "Tümü", exact: true }).click();
  assert.equal(await schedule.locator("button[aria-pressed]").filter({ has: founder.locator("h3") }).count(), 9);
  await schedule.screenshot({ path: join(tmpdir(), "lidea-training-panel-desktop.png") });
  await founder.setViewportSize({ width: 390, height: 844 });
  assert.equal(await founder.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await schedule.screenshot({ path: join(tmpdir(), "lidea-training-panel-mobile.png") });
  await admin.setViewportSize({ width: 390, height: 844 });
  assert.equal(await admin.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, "Admin tabs must not overflow");
  await founder.getByRole("button", { name: /^Bildirimler \(/ }).click();
  await founder.getByRole("button", { name: "Eğitimi Görüntüle" }).first().click();
  await founder.getByRole("region", { name: "Eğitim takvimi", exact: true }).waitFor();
  await admin.getByRole("button", { name: "Bağlantı ve Saati Düzenle", exact: true }).click();
  await admin.getByLabel("Durum", { exact: true }).selectOption("cancelled");
  await admin.getByRole("button", { name: "Eğitimi Kaydet", exact: true }).click();
  await founder.waitForFunction(() => [...document.querySelectorAll("button")].some((button) => button.textContent === "Eğitime Katıl" && button.disabled));
  const publicPage = await context.newPage();
  await publicPage.goto(`${origin}/#takvim`);
  await publicPage.waitForFunction(() => document.querySelector("#takvim")?.textContent.includes("İptal edildi"));
  const publicText = await publicPage.locator("#takvim").innerText();
  assert.ok(publicText.includes("20:00")); assert.ok(!publicText.includes("https://zoom.us"));
  const login = await context.request.post(`${origin}/api/auth/entrepreneur`, { data: { email: "tester@lideagirisim.com", password: "1234567890" } });
  assert.equal(login.status(), 200);
  const denied = await context.request.patch(`${origin}/api/trainings/${id}`, { data: {} });
  assert.equal(denied.status(), 403, "A real entrepreneur session cannot edit training links");
  const serverContext = await browser.newContext();
  try {
    const snapshot = await founder.evaluate(() => JSON.parse(localStorage.getItem("lidea-training-schedule"))[0]);
    await serverContext.route("**/api/auth/entrepreneur", (route) => route.fulfill({ json: { ok: true, user: { name: "Gerçek Girişimci", email: "real@example.com", role: "Girişimci", localWorkspace: false } } }));
    await serverContext.route("**/api/entrepreneur/me", (route) => route.fulfill({ json: { application: null, startup: null, notifications: [] } }));
    await serverContext.route("**/api/trainings?*", (route) => route.fulfill({ json: { trainings: [{ ...snapshot, status: "scheduled", following: false }], remindersSent: 0 } }));
    const signed = await serverContext.newPage();
    await signed.goto(`${origin}/girisimci?egitim=${id}`);
    await signed.getByText("Gerçek Girişimci", { exact: true }).waitFor();
    const joinLink = signed.getByRole("region", { name: "Eğitim takvimi", exact: true }).getByRole("link", { name: "Eğitime Katıl", exact: true });
    await joinLink.waitFor();
    assert.equal(await joinLink.getAttribute("href"), `/api/trainings/${id}/join`);
    assert.equal(await signed.getByRole("button", { name: "Bağlantı ve Saati Düzenle", exact: true }).count(), 0);
    await serverContext.route("**/api/trainings?view=admin", (route) => route.fulfill({ status: 403, json: { ok: false } }));
    await serverContext.route("**/api/auth/admin", (route) => route.fulfill({ json: { ok: true, localWorkspace: false, user: { role: "SUPER_ADMIN", email: "admin@lideagirisim.com" } } }));
    const forbidden = await serverContext.newPage();
    await forbidden.goto(`${origin}/admin/program?egitim=${id}`);
    await forbidden.getByText("Bu eğitim takvimine erişim için uygun yetkili oturum gerekli.", { exact: true }).waitFor();
    assert.equal(await forbidden.getByRole("button", { name: "Bağlantı ve Saati Düzenle", exact: true }).count(), 0);
  } finally { await serverContext.close(); }
  console.log("PASS: admin link/time editing, readonly entrepreneur controls, follow/host reminders, updated link popup, calendar download, notification deep link, cancellation, public metadata privacy and mobile layout.");
} finally { await context.close(); await browser.close(); }
